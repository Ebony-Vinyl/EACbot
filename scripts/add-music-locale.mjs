/** Appends `entries` to a JSON object file as text, keeping every existing byte. */
function appendEntries(file, entries) {
  const text = readFileSync(file, "utf8");
  const existing = JSON.parse(text);
  const missing = Object.entries(entries).filter(([key]) => !Object.hasOwn(existing, key));
  if (!missing.length) return 0;
  const closing = text.lastIndexOf("}");
  if (closing < 0) throw new Error(`${file} is not a JSON object`);
  const before = text.slice(0, closing).replace(/\s*$/, "");
  const needsComma = !/[{,]\s*$/.test(before) && before.trim() !== "{";
  const body = missing.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(",\n");
  const next = `${before}${needsComma ? "," : ""}\n${body}\n}\n`;
  // The result must still parse, and must hold every key it held before.
  const parsed = JSON.parse(next);
  for (const key of Object.keys(existing)) if (!Object.hasOwn(parsed, key)) throw new Error(`${file}: ${key} would be lost`);
  writeFileSync(file, next);
  return missing.length;
}

function sourceHash(value) {
  return createHash("sha256").update(String(value)).digest("hex");
}

const enAdded = appendEntries(join(LOCALES, "en.json"), EN);
const zhAdded = appendEntries(join(LOCALES, "zh.json"), ZH);

// Only the new strings need a hash; the rest of the file is left exactly as it was.
const hashFile = join(LOCALES, "source-hashes.json");
const hashes = JSON.parse(readFileSync(hashFile, "utf8"));
let hashed = 0;
for (const [key, value] of Object.entries(EN)) {
  if (hashes[key] === sourceHash(value)) continue;
  hashes[key] = sourceHash(value);
  hashed += 1;
}
writeFileSync(hashFile, `${JSON.stringify(hashes, null, 2)}\n`);

